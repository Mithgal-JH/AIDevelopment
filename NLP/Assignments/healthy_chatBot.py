# 5) تشغيل البوت
# ---------------------------------


def run_bot():

    print("🤖 البوت الطبي جاهز. اكتب (خروج) لإنهاء المحادثة.")

    while True:

        user_input = input("أنت: ")

        if user_input == "خروج":
            print("البوت: أتمنى لك الصحة والعافية.")
            break

        reply, intent = get_bot_reply(user_input)

        print("Intent:", intent)
        print("البوت:", reply)


run_bot()
